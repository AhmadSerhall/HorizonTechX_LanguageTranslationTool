const normalizeCode = (languageCode = '') => languageCode.replace(/_/g, '-').toLocaleLowerCase();

export const getUiTranslation = (languageCode) => {
  const normalizedCode = normalizeCode(languageCode);
  const exactCode = Object.keys(uiTranslations).find((code) => normalizeCode(code) === normalizedCode);
  if (exactCode) return uiTranslations[exactCode];

  const baseCode = normalizedCode.split('-')[0];
  const baseMatch = Object.keys(uiTranslations).find((code) => normalizeCode(code) === baseCode);
  return baseMatch ? uiTranslations[baseMatch] : uiTranslations.en;
};

